"""Deterministic local views, with no network access or automatic promotion."""

import json
import os
import statistics
import tempfile
from collections import defaultdict
from pathlib import Path

from flbench.records import published_records
from flbench.repository import (CONFIG, COST, MANIFEST, OWNERS, file_hash, load_json,
                                protocol_hash, readiness_errors)


def rank_groups(records, *, expected):
    groups = defaultdict(list)
    for record in records:
        if any(record[key] != value for key, value in expected.items() if key != "seeds"):
            continue
        if record["status"] != "complete":
            continue
        key = (record["owner"], record["method_id"], record["git_commit"], record["config_hash"])
        groups[key].append(record)
    rows = []
    seeds = sorted(expected["seeds"])
    for key, runs in groups.items():
        # Equality also rejects duplicate seeds, rather than cherry-picking their best score.
        if sorted(run["seed"] for run in runs) != seeds:
            continue
        scores = [run["j_dev"] for run in runs]
        rows.append({"owner": key[0], "method_id": key[1], "git_commit": key[2],
                     "config_hash": key[3], "mean": statistics.mean(scores),
                     "sd": statistics.stdev(scores) if len(scores) > 1 else 0.0,
                     "run_ids": sorted(run["run_id"] for run in runs)})
    return sorted(rows, key=lambda row: (-row["mean"], row["method_id"], row["owner"],
                                         row["git_commit"], row["config_hash"]))


def generated_views(root: Path) -> dict[str, str]:
    records = published_records(root)  # Validate everything before writing any view.
    config = load_json(root / CONFIG)
    runtime = load_json(root / "configs/environment/runtime.json")
    evaluation = config["evaluation"]
    blockers = readiness_errors(root)
    rows = []
    if not blockers:
        expected = {
            "protocol_hash": protocol_hash(root), "data_hash": load_json(root / MANIFEST)["content_sha256"],
            "cost_hash": file_hash(root / COST), "budget_sim_seconds": evaluation["budget_sim_seconds"],
            "scenario": evaluation["primary_scenario"], "stage": "development",
            "evaluation_scope": "search_validation", "fidelity": "full",
            "seeds": evaluation["development_seeds"],
        }
        rows = rank_groups(records, expected=expected)
    board = ["# 开发排行榜", "", "<!-- Generated by scripts/sync_leaderboard.py; do not edit. -->", "",
             "仅展示当前冻结协议下主场景、完整 B 与完整开发种子的结果；不自动晋级。", ""]
    if rows:
        board.extend(["| 排名 | 方法 | 工作区 | 平均 Macro-F1 | 标准差 | 实现 commit / 配置 | run IDs |",
                      "| --- | --- | --- | --- | --- | --- | --- |"])
        for index, row in enumerate(rows, 1):
            board.append(f"| {index} | {row['method_id']} | {row['owner']} | {row['mean']:.6f} | "
                         f"{row['sd']:.6f} | {row['git_commit'][:12]} / {row['config_hash'][:12]} | "
                         f"{', '.join(row['run_ids'])} |")
    else:
        board.append("暂无可入榜的真实完整实验。")
    if blockers:
        board.extend(["", "当前仍处于基础建设阶段；就绪阻碍见 GLOBAL_STATUS.md。"])
    status = ["# 全局状态", "", "<!-- Generated by scripts/sync_leaderboard.py; do not edit. -->", "",
              f"- 当前阶段：`{config['phase']}`", f"- 协议版本：`{config['protocol_version']}`",
              f"- 协议状态：`{config['status']}`",
              f"- 统一环境：uv `{runtime['uv']}` / CPython `{runtime['python']}` / `{runtime['profile']}`；每份 checkout 独立 `.venv`。",
              f"- 模拟预算 B：`{evaluation['budget_sim_seconds']}`（null 表示尚未标定）",
              f"- 已发布终态记录：{len(records)}；可入开发主榜的方法组：{len(rows)}。",
              "- Champion 指针见 CHAMPION_DEV.json / CHAMPION_FINAL.json；初始为空。", "",
              "| 工作区 | 已发布记录 | 成功 | 失败/超时/无效 | 交接入口 |",
              "| --- | --- | --- | --- | --- |"]
    for owner in OWNERS:
        owned = [record for record in records if record["owner"] == owner]
        complete = sum(record["status"] == "complete" for record in owned)
        status.append(f"| {owner} | {len(owned)} | {complete} | {len(owned) - complete} | "
                      f"[HANDOFF](../agents/{owner}/HANDOFF.md) |")
    status.extend(["", "## 尚未满足的就绪条件", ""])
    status.extend(f"- {error}" for error in blockers)
    if not blockers:
        status.append("工程清单已就绪；仍须人工确认数据/训练证据与搜索授权。")
    status.extend(["", "本视图只汇总当前检出的记录；进行中任务见个人 HANDOFF，不代表远端其他分支或进程实时状态。"])
    return {
        "shared/LEADERBOARD.md": "\n".join(board) + "\n",
        "shared/GLOBAL_STATUS.md": "\n".join(status) + "\n",
        "shared/EXPERIMENT_INDEX.jsonl": "".join(
            json.dumps(record, ensure_ascii=False, sort_keys=True, allow_nan=False) + "\n"
            for record in records),
    }


def synchronize(root: Path, *, check: bool = False) -> list[str]:
    views = generated_views(root)
    changed = []
    for name, content in views.items():
        path = root / name
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        changed.append(name)
        if check:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                             dir=path.parent, suffix=".tmp", delete=False) as handle:
                temporary = Path(handle.name)
                handle.write(content)
            os.replace(temporary, path)
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)
    return changed
